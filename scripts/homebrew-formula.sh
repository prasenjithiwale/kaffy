#!/bin/sh
# Prints the Homebrew formula for a release, from the archives' checksum files.
#
#   scripts/homebrew-formula.sh v0.4.0 dist/ > Formula/kaffy.rb
#
# The release workflow runs this and pushes the result to
# github.com/prasenjithiwale/homebrew-tap. The binaries stay on the folio site.

set -eu

tag=$1
dist=$2
site=${KAFFY_RELEASES_URL:-https://prasenjithiwale.github.io/folio/kaffy/releases}

sha() {
    file="$dist/kaffy-$tag-$1.tar.gz.sha256"
    [ -f "$file" ] || { echo "missing $file" >&2; exit 1; }
    cut -d' ' -f1 "$file"
}

url() { printf '%s/%s/kaffy-%s-%s.tar.gz' "$site" "$tag" "$tag" "$1"; }

cat <<EOF
# Generated by kaffy's release workflow (scripts/homebrew-formula.sh) for $tag.
# Edits made here are overwritten by the next release.
class Kaffy < Formula
  desc "Terminal UI for exploring and operating Kafka clusters"
  homepage "https://prasenjithiwale.github.io/folio/kaffy/"
  version "${tag#v}"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "$(url aarch64-apple-darwin)"
      sha256 "$(sha aarch64-apple-darwin)"
    end
    on_intel do
      url "$(url x86_64-apple-darwin)"
      sha256 "$(sha x86_64-apple-darwin)"
    end
  end

  on_linux do
    on_intel do
      url "$(url x86_64-unknown-linux-musl)"
      sha256 "$(sha x86_64-unknown-linux-musl)"
    end
    on_arm do
      url "$(url aarch64-unknown-linux-musl)"
      sha256 "$(sha aarch64-unknown-linux-musl)"
    end
  end

  def install
    bin.install "kaffy"
    pkgshare.install "config.example.toml"
    doc.install "THIRD-PARTY-LICENSES.txt"
    prefix.install "LICENSE-MIT", "LICENSE-APACHE"
  end

  def caveats
    <<~EOS
      Try it without a broker:  kaffy --demo
      Example config:           #{pkgshare}/config.example.toml
                                (copy it to ~/.config/kaffy/config.toml)
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/kaffy --version")
  end
end
EOF
